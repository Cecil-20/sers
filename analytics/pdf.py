from io import BytesIO
from xml.sax.saxutils import escape

from django.db.models import Avg, Count, DurationField, ExpressionWrapper, F, Q
from django.utils import timezone
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from teams.models import EmergencyCategory, ResponseTeam

RESPONSE_TIME = ExpressionWrapper(
  F('resolved_at') - F('created_at'), output_field=DurationField()
)
STATUS_ORDER = ['submitted', 'assigned', 'in_progress', 'resolved', 'closed']
STATUS_LABELS = {
  'submitted': 'Submitted', 'assigned': 'Assigned', 'in_progress': 'In progress',
  'resolved': 'Resolved', 'closed': 'Closed',
}
SEVERITY_ORDER = ['low', 'medium', 'high', 'critical']
METHOD_LABELS = {'form': 'Web form', 'hotline': 'Hotline call'}

INK = colors.HexColor('#1f2933')
MUTED = colors.HexColor('#52606d')
RULE = colors.HexColor('#cbd2d9')
HEAD_BG = colors.HexColor('#e4e7eb')


def _duration(delta):
  if not delta:
    return 'No data'
  minutes = round(delta.total_seconds() / 60)
  days, rest = divmod(minutes, 1440)
  hours, mins = divmod(rest, 60)
  if days:
    return f'{days}d {hours}h {mins}m'
  if hours:
    return f'{hours}h {mins}m'
  return f'{mins}m'


def _stamp(value):
  if not value:
    return '-'
  return timezone.localtime(value).strftime('%d %b %Y %H:%M')


def _styles():
  base = getSampleStyleSheet()
  return {
    'title': ParagraphStyle('title', parent=base['Title'], fontSize=20, leading=24,
                            alignment=0, textColor=INK, spaceAfter=2),
    'sub': ParagraphStyle('sub', parent=base['Normal'], fontSize=10,
                          textColor=MUTED, spaceAfter=8),
    'h2': ParagraphStyle('h2', parent=base['Heading2'], fontSize=12,
                         textColor=INK, spaceBefore=4, spaceAfter=4),
    'body': ParagraphStyle('body', parent=base['Normal'], fontSize=9, textColor=INK),
    'cell': ParagraphStyle('cell', parent=base['Normal'], fontSize=8, leading=10,
                           textColor=INK),
    'head': ParagraphStyle('head', parent=base['Normal'], fontName='Helvetica-Bold',
                           fontSize=8, leading=10, textColor=INK),
  }


def _data_table(header, rows, widths, styles):
  data = [[Paragraph(escape(h), styles['head']) for h in header]]
  for row in rows:
    data.append([Paragraph(escape(str(v)), styles['cell']) for v in row])
  table = Table(data, colWidths=widths, repeatRows=1)
  table.setStyle(TableStyle([
    ('BACKGROUND', (0, 0), (-1, 0), HEAD_BG),
    ('LINEBELOW', (0, 0), (-1, -1), 0.4, RULE),
    ('VALIGN', (0, 0), (-1, -1), 'TOP'),
    ('TOPPADDING', (0, 0), (-1, -1), 3),
    ('BOTTOMPADDING', (0, 0), (-1, -1), 3),
  ]))
  return table


def _section(story, styles, title, header, rows, widths):
  story.append(Paragraph(escape(title), styles['h2']))
  if rows:
    story.append(_data_table(header, rows, widths, styles))
  else:
    story.append(Paragraph('No data for the selected filters.', styles['body']))
  story.append(Spacer(1, 6 * mm))


def _filter_lines(applied):
  lines = []
  if 'date_from' in applied or 'date_to' in applied:
    lines.append(
      f"Date: {applied.get('date_from', 'start')} to {applied.get('date_to', 'today')}"
    )
  if 'category' in applied:
    name = (EmergencyCategory.objects.filter(pk=applied['category'])
            .values_list('category_name', flat=True).first())
    lines.append(f"Category: {name or applied['category']}")
  if 'team' in applied:
    name = (ResponseTeam.objects.filter(pk=applied['team'])
            .values_list('team_name', flat=True).first())
    lines.append(f"Team: {name or applied['team']}")
  if 'severity' in applied:
    lines.append(f"Severity: {applied['severity']}")
  return lines or ['None (all incidents in scope)']


def _front_matter(story, styles, user, own_team, applied, total):
  if user.role == 'general_admin':
    scope = 'All teams'
  else:
    scope = own_team.team_name if own_team else 'Team'
  who = getattr(user, 'full_name', None) or user.email
  story.append(Paragraph('SERIMS Incident Report', styles['title']))
  story.append(Paragraph(escape(f'Scope: {scope}'), styles['sub']))
  rows = [
    ['Generated by', who],
    ['Generated at', timezone.localtime().strftime('%d %b %Y, %H:%M')],
    ['Filters', ' | '.join(_filter_lines(applied))],
    ['Incidents in report', total],
  ]
  story.append(_data_table(['Detail', 'Value'], rows, [40 * mm, 140 * mm], styles))
  story.append(Spacer(1, 6 * mm))


def _summary(story, styles, qs, is_admin):
  resolved = qs.filter(resolved_at__isnull=False)
  rows = [
    ['Total incidents', qs.count()],
    ['Resolved', resolved.count()],
    ['Hotline calls', qs.filter(report_method='hotline').count()],
  ]
  if not is_admin:
    avg = resolved.annotate(rt=RESPONSE_TIME).aggregate(a=Avg('rt'))['a']
    rows.append(['Average response time', _duration(avg)])
  _section(story, styles, 'Summary', ['Measure', 'Value'], rows, [90 * mm, 90 * mm])


def _teams(story, styles, qs):
  data = (
    qs.values('team__team_name')
    .annotate(
      total=Count('id'),
      resolved=Count('id', filter=Q(resolved_at__isnull=False)),
      avg_rt=Avg(RESPONSE_TIME, filter=Q(resolved_at__isnull=False)),
    )
    .order_by('team__team_name')
  )
  rows = [
    [r['team__team_name'] or 'Unassigned', r['total'], r['resolved'], _duration(r['avg_rt'])]
    for r in data
  ]
  _section(story, styles, 'Response time by team',
           ['Team', 'Incidents', 'Resolved', 'Avg response time'], rows,
           [60 * mm, 30 * mm, 30 * mm, 60 * mm])


def _breakdowns(story, styles, qs):
  half = [90 * mm, 90 * mm]
  by_status = dict(qs.values_list('status').annotate(c=Count('id')).order_by())
  rows = [[STATUS_LABELS[s], by_status.get(s, 0)] for s in STATUS_ORDER]
  _section(story, styles, 'Incidents by status', ['Status', 'Incidents'], rows, half)

  by_sev = dict(qs.values_list('ai_severity').annotate(c=Count('id')).order_by())
  rows = [[s.title(), by_sev.get(s, 0)] for s in SEVERITY_ORDER]
  if by_sev.get(None):
    rows.append(['Unclassified', by_sev[None]])
  _section(story, styles, 'Incidents by severity', ['Severity', 'Incidents'], rows, half)

  by_cat = qs.values_list('category__category_name').annotate(c=Count('id')).order_by('-c')
  rows = [[name or 'Uncategorized', c] for name, c in by_cat]
  _section(story, styles, 'Incidents by category', ['Category', 'Incidents'], rows, half)

  by_method = dict(qs.values_list('report_method').annotate(c=Count('id')).order_by())
  rows = [[METHOD_LABELS.get(k, k), v] for k, v in by_method.items()]
  _section(story, styles, 'How incidents were reported', ['Method', 'Incidents'], rows, half)


def _hotline(story, styles, qs):
  calls = qs.filter(report_method='hotline').select_related('team').order_by('-created_at')[:50]
  rows = [
    [c.reference_no, c.caller_number or '-', c.team.team_name if c.team else '-',
     STATUS_LABELS.get(c.status, c.status), _stamp(c.created_at)]
    for c in calls
  ]
  _section(story, styles, 'Hotline calls (latest 50)',
           ['Reference', 'Caller', 'Team', 'Status', 'Received'], rows,
           [34 * mm, 34 * mm, 38 * mm, 28 * mm, 46 * mm])


def _incident_list(story, styles, qs):
  items = qs.select_related('category', 'team').order_by('-created_at')[:200]
  rows = [
    [i.reference_no,
     i.category.category_name if i.category else '-',
     i.ai_severity or '-',
     STATUS_LABELS.get(i.status, i.status),
     i.team.team_name if i.team else '-',
     _stamp(i.created_at),
     _stamp(i.resolved_at)]
    for i in items
  ]
  _section(story, styles, 'Incidents (latest 200)',
           ['Reference', 'Category', 'Severity', 'Status', 'Team', 'Reported', 'Resolved'],
           rows,
           [32 * mm, 30 * mm, 18 * mm, 22 * mm, 28 * mm, 25 * mm, 25 * mm])


def _footer(canvas, doc):
  canvas.saveState()
  canvas.setFont('Helvetica', 8)
  canvas.setFillColor(MUTED)
  canvas.drawString(15 * mm, 10 * mm, 'SERIMS - Smart Emergency Response and Incident Management System')
  canvas.drawRightString(195 * mm, 10 * mm, f'Page {doc.page}')
  canvas.restoreState()


def build_report_pdf(qs, user, own_team, applied):
  styles = _styles()
  is_admin = user.role == 'general_admin'
  story = []
  _front_matter(story, styles, user, own_team, applied, qs.count())
  _summary(story, styles, qs, is_admin)
  if is_admin:
    _teams(story, styles, qs)
  _breakdowns(story, styles, qs)
  _hotline(story, styles, qs)
  _incident_list(story, styles, qs)

  buffer = BytesIO()
  doc = SimpleDocTemplate(
    buffer, pagesize=A4, leftMargin=15 * mm, rightMargin=15 * mm,
    topMargin=15 * mm, bottomMargin=18 * mm,
    title='SERIMS Incident Report', author=user.email,
  )
  doc.build(story, onFirstPage=_footer, onLaterPages=_footer)
  return buffer.getvalue()
