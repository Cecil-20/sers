from decouple import config as _env
from django.core.exceptions import ImproperlyConfigured

ADMIN_URL = _env('ADMIN_URL', default='admin/')
if not ADMIN_URL.endswith('/'):
  ADMIN_URL += '/'

if not DEBUG:
  ALLOWED_HOSTS = [h.strip() for h in _env('ALLOWED_HOSTS', default='').split(',') if h.strip()]
  CSRF_TRUSTED_ORIGINS = [o.strip() for o in _env('CSRF_TRUSTED_ORIGINS', default='').split(',') if o.strip()]
  if not ALLOWED_HOSTS:
    raise ImproperlyConfigured('Set ALLOWED_HOSTS (comma separated) when DEBUG is off.')
  if SECRET_KEY.startswith('django-insecure-') or len(SECRET_KEY) < 50:
    raise ImproperlyConfigured('Set a strong, unique SECRET_KEY when DEBUG is off.')

  # HTTPS everywhere. The proxy in front (Railway, Render, Nginx...) must send
  # X-Forwarded-Proto, and NUM_PROXIES is how many proxies sit in front, so the
  # throttles see each visitor's real address instead of the proxy's.
  SECURE_PROXY_SSL_HEADER = ('HTTP_X_FORWARDED_PROTO', 'https')
  SECURE_SSL_REDIRECT = _env('SECURE_SSL_REDIRECT', default=True, cast=bool)
  SECURE_REDIRECT_EXEMPT = [r'^healthz/$']
  SESSION_COOKIE_SECURE = True
